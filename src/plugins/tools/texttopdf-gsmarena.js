const axios = require('axios');
const h = require('../../lib/helpers');
const fs = require('fs-extra');
const path = require('path');

module.exports = [

  {
    command: 'texttopdf',
    aliases: ['txt2pdf', 'makepdff'],
    category: 'soultools',
    description: 'Convert plain text to a downloadable PDF. Usage: .texttopdf <your text>',
    execute: async ({ sock, msg, chatId, text, args, reply }) => {
      const content = text || args.join(' ');
      if (!content) return reply(h.demonError('.texttopdf', '.texttopdf <your text here>', 'Give me text to convert, clown.'));
      try {
        const { PDFDocument, rgb, StandardFonts } = require('pdf-lib');
        const pdfDoc = await PDFDocument.create();
        const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
        const fontSize = 12;
        const margin = 50;
        const pageWidth = 595, pageHeight = 842;
        const maxWidth = pageWidth - margin * 2;
        const lineHeight = fontSize * 1.5;

        const words = content.split(' ');
        const lines = [];
        let currentLine = '';
        for (const word of words) {
          const testLine = currentLine ? `${currentLine} ${word}` : word;
          const width = font.widthOfTextAtSize(testLine, fontSize);
          if (width > maxWidth && currentLine) {
            lines.push(currentLine);
            currentLine = word;
          } else {
            currentLine = testLine;
          }
        }
        if (currentLine) lines.push(currentLine);

        // Handle newlines in original content
        const expandedLines = [];
        for (const rawLine of content.split('\n')) {
          const lineWords = rawLine.split(' ');
          let cur = '';
          for (const w of lineWords) {
            const test = cur ? `${cur} ${w}` : w;
            if (font.widthOfTextAtSize(test, fontSize) > maxWidth && cur) {
              expandedLines.push(cur);
              cur = w;
            } else cur = test;
          }
          if (cur) expandedLines.push(cur);
          expandedLines.push(''); // blank line for paragraph
        }

        const linesPerPage = Math.floor((pageHeight - margin * 2) / lineHeight);
        const chunks = [];
        for (let i = 0; i < expandedLines.length; i += linesPerPage) {
          chunks.push(expandedLines.slice(i, i + linesPerPage));
        }

        for (const chunk of chunks) {
          const page = pdfDoc.addPage([pageWidth, pageHeight]);
          let y = pageHeight - margin;
          for (const line of chunk) {
            page.drawText(line, { x: margin, y, size: fontSize, font, color: rgb(0,0,0) });
            y -= lineHeight;
          }
          // Footer
          page.drawText('Generated by Crittix MD', { x: margin, y: margin / 2, size: 8, font, color: rgb(0.5,0.5,0.5) });
        }

        const pdfBytes = await pdfDoc.save();
        const tmpPath = path.join(process.cwd(), 'tmp', `text_${Date.now()}.pdf`);
        fs.ensureDirSync(path.dirname(tmpPath));
        fs.writeFileSync(tmpPath, pdfBytes);

        await sock.sendMessage(chatId, {
          document: { url: tmpPath },
          mimetype: 'application/pdf',
          fileName: 'crittix-text.pdf',
          caption: `📄 *Text → PDF*\n\n${expandedLines.filter(Boolean).length} lines, ${chunks.length} page(s)\n\n_𝗖𝗿𝗶𝘁𝘁𝗶𝘅 𝗠𝗗_`
        }, { quoted: msg });

        fs.removeSync(tmpPath);
      } catch (e) {
        reply(h.demonFail(`PDF generation failed: ${e.message}\nMake sure pdf-lib is installed.`));
      }
    }
  },

  {
    command: 'gsmarena',
    aliases: ['phonespec', 'specphone'],
    category: 'soultools',
    description: 'Look up phone specs on GSMArena. Usage: .gsmarena Samsung Galaxy S24',
    execute: async ({ text, args, reply }) => {
      const query = text || args.join(' ');
      if (!query) return reply(h.demonError('.gsmarena', '.gsmarena <phone model>', 'e.g. .gsmarena iPhone 15 Pro'));
      try {
        const cheerio = require('cheerio');
        const searchUrl = `https://www.gsmarena.com/results.php3?sQuickSearch=yes&sName=${encodeURIComponent(query)}`;
        const searchRes = await axios.get(searchUrl, {
          headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36' },
          timeout: 15000
        });
        const $ = cheerio.load(searchRes.data);
        const firstResult = $('.makers ul li a').first();
        if (!firstResult.length) return reply(h.demonFail(`No results for "${query}" on GSMArena. It doesn't exist or you typed wrong.`));

        const deviceUrl = 'https://www.gsmarena.com' + firstResult.attr('href');
        const deviceRes = await axios.get(deviceUrl, {
          headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36' },
          timeout: 15000
        });
        const $d = cheerio.load(deviceRes.data);

        const name = $d('h1.specs-phone-name-title').text().trim() || firstResult.find('span').last().text().trim();
        const specs = {};
        $d('.specs-list tr').each((_, row) => {
          const label = $d(row).find('.ttl a, .ttl span').text().trim();
          const value = $d(row).find('.nfo a, .nfo').text().trim();
          if (label && value && label.length < 30) specs[label] = value;
        });

        const keySpecs = ['Network', 'Launch', 'Body', 'Display', 'Platform', 'Memory', 'Main Camera', 'Battery', 'Comms'];
        let msg = `📱 *${name}*\n🔗 ${deviceUrl}\n\n`;
        for (const k of keySpecs) {
          if (specs[k]) msg += `*${k}:* ${specs[k].substring(0,120)}\n`;
        }
        if (!Object.keys(specs).length) msg += '_Specs not parsed properly. Visit the link above._\n';
        msg += `\n_𝗖𝗿𝗶𝘁𝘁𝗶𝘅 𝗠𝗗_`;
        reply(msg);
      } catch (e) {
        reply(h.demonFail(`GSMArena scrape failed: ${e.message}`));
      }
    }
  }

];
